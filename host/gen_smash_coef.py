"""Writes src/smash_coef.inc: the Butterworth sections of Smash's two Linkwitz-Riley crossovers (88.3 Hz, 2.5 kHz at 48 kHz)."""
import math
import os

FS = 48000.0


def sections(hz):
    w = 2 * math.pi * hz / FS
    c, a = math.cos(w), math.sin(w) / (2 * math.sqrt(0.5))
    a0 = 1 + a
    lp = [(1 - c) / 2 / a0, (1 - c) / a0, (1 - c) / 2 / a0, -2 * c / a0, (1 - a) / a0]
    hp = [(1 + c) / 2 / a0, -(1 + c) / a0, (1 + c) / 2 / a0, -2 * c / a0, (1 - a) / a0]
    ap = [(1 - a) / a0, -2 * c / a0, 1.0, -2 * c / a0, (1 - a) / a0]
    return lp, hp, ap


def row(name, v):
    return f"static const float {name}[5] = {{" + ", ".join(f"{x:.9e}f" for x in v) + "};\n"


lo, hi = sections(88.3), sections(2500.0)
out = "/* generated by host/gen_smash_coef.py: b0 b1 b2 a1 a2 */\n"
out += row("xo_lp1", lo[0]) + row("xo_hp1", lo[1]) + row("xo_lp2", hi[0]) + row("xo_hp2", hi[1]) + row("xo_ap2", hi[2])
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "smash_coef.inc"), "w").write(out)
print(out)
